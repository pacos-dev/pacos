CREATE SEQUENCE IF NOT EXISTS APP_NOTIFICATION_MESSAGE_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS APP_NOTIFICATION_OPERATION_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS APP_NOTIFICATION_OPERATION_EVENT_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS APP_NOTIFICATION_USER_STATE_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS APP_NOTIFICATION_MESSAGE
(
    id                         BIGINT PRIMARY KEY NOT NULL,
    title                      VARCHAR(255) NOT NULL,
    summary                    VARCHAR(1000),
    body                       VARCHAR(12000),
    source_key                 VARCHAR(100) NOT NULL,
    category                   VARCHAR(32) NOT NULL,
    priority                   VARCHAR(32) NOT NULL,
    created_at                 TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at                 TIMESTAMP WITH TIME ZONE,
    action_url                 VARCHAR(2048),
    requires_acknowledgement   BOOLEAN DEFAULT FALSE NOT NULL,
    active                     BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_APP_NOTIFICATION_MESSAGE_CREATED
    ON APP_NOTIFICATION_MESSAGE (created_at);
CREATE INDEX IF NOT EXISTS IDX_APP_NOTIFICATION_MESSAGE_SOURCE
    ON APP_NOTIFICATION_MESSAGE (source_key);

CREATE TABLE IF NOT EXISTS APP_NOTIFICATION_OPERATION
(
    id             BIGINT PRIMARY KEY NOT NULL,
    title          VARCHAR(255) NOT NULL,
    summary        VARCHAR(1000),
    details        VARCHAR(12000),
    source_key     VARCHAR(100) NOT NULL,
    priority       VARCHAR(32) NOT NULL,
    status         VARCHAR(32) NOT NULL,
    progress       INTEGER,
    current_step   VARCHAR(255),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at     TIMESTAMP WITH TIME ZONE,
    finished_at    TIMESTAMP WITH TIME ZONE,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_APP_NOTIFICATION_OPERATION_CREATED
    ON APP_NOTIFICATION_OPERATION (created_at);
CREATE INDEX IF NOT EXISTS IDX_APP_NOTIFICATION_OPERATION_STATUS
    ON APP_NOTIFICATION_OPERATION (status);

CREATE TABLE IF NOT EXISTS APP_NOTIFICATION_OPERATION_EVENT
(
    id             BIGINT PRIMARY KEY NOT NULL,
    operation_id   BIGINT NOT NULL,
    event_type     VARCHAR(64) NOT NULL,
    message        VARCHAR(2000),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT FK_NOTIFICATION_EVENT_OPERATION
        FOREIGN KEY (operation_id) REFERENCES APP_NOTIFICATION_OPERATION (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS IDX_APP_NOTIFICATION_EVENT_OPERATION
    ON APP_NOTIFICATION_OPERATION_EVENT (operation_id, created_at);

CREATE TABLE IF NOT EXISTS APP_NOTIFICATION_USER_STATE
(
    id                BIGINT PRIMARY KEY NOT NULL,
    user_id           INTEGER NOT NULL,
    item_type         VARCHAR(20) NOT NULL,
    item_id           BIGINT NOT NULL,
    read_at           TIMESTAMP WITH TIME ZONE,
    acknowledged_at   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT FK_NOTIFICATION_STATE_USER
        FOREIGN KEY (user_id) REFERENCES APP_USER (id) ON DELETE CASCADE,
    CONSTRAINT UQ_NOTIFICATION_USER_ITEM UNIQUE (user_id, item_type, item_id)
);
CREATE INDEX IF NOT EXISTS IDX_APP_NOTIFICATION_STATE_USER
    ON APP_NOTIFICATION_USER_STATE (user_id, read_at);
