ALTER TABLE APP_USER
    ADD COLUMN IF NOT EXISTS ONBOARDING_DISMISSED BOOLEAN DEFAULT FALSE NOT NULL;

UPDATE APP_USER
SET ONBOARDING_DISMISSED = TRUE
WHERE ID = 2
  AND EXISTS (
      SELECT 1
      FROM APP_REGISTRY
      WHERE REGISTRY_NAME = 'ONBOARDING_DISMISSED'
        AND LOWER(VALUE) = 'true'
  );

DELETE FROM APP_REGISTRY
WHERE REGISTRY_NAME IN ('SETUP_OWNER_USER_ID', 'ONBOARDING_DISMISSED');
