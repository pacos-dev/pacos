CREATE TABLE IF NOT EXISTS APP_PLUGIN_REPOSITORY
(
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REPOSITORY_NAME VARCHAR(120) NOT NULL,
    REPOSITORY_URL VARCHAR(2048) NOT NULL,
    CONSTRAINT UK_APP_PLUGIN_REPOSITORY_NAME UNIQUE (REPOSITORY_NAME),
    CONSTRAINT UK_APP_PLUGIN_REPOSITORY_URL UNIQUE (REPOSITORY_URL)
);
